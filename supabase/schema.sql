-- Groove: synced library schema (run once in the Supabase SQL editor or as a migration)

create table if not exists public.tracks (
  id            text primary key,                     -- id generated by the app
  user_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title         text not null,
  artist        text,
  kind          text not null check (kind in ('audio','video')),
  embed         text check (embed in ('yt','tt')),    -- YouTube / TikTok
  vid           text,                                 -- YouTube / TikTok video id
  link          text,                                 -- original link (stream links and embeds)
  storage_path  text,                                 -- file in the 'songs' bucket: <user_id>/<id>.<ext>
  mime          text,
  size          bigint,
  duration      double precision,
  tall          boolean not null default false,
  added         bigint not null,                      -- ms timestamp, keeps library order
  studio        jsonb,                                -- beat pattern for songs made in the Studio
  created_at    timestamptz not null default now()
);
create index if not exists tracks_user_added_idx on public.tracks (user_id, added);

alter table public.tracks enable row level security;
create policy "own tracks: read"   on public.tracks for select to authenticated using ((select auth.uid()) = user_id);
create policy "own tracks: add"    on public.tracks for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "own tracks: change" on public.tracks for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "own tracks: remove" on public.tracks for delete to authenticated using ((select auth.uid()) = user_id);

-- Private bucket for uploaded songs and videos (50 MB per file, the free-plan maximum)
insert into storage.buckets (id, name, public, file_size_limit)
values ('songs', 'songs', false, 52428800)
on conflict (id) do nothing;

create policy "own files: read"   on storage.objects for select to authenticated
  using (bucket_id = 'songs' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "own files: add"    on storage.objects for insert to authenticated
  with check (bucket_id = 'songs' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "own files: change" on storage.objects for update to authenticated
  using (bucket_id = 'songs' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "own files: remove" on storage.objects for delete to authenticated
  using (bucket_id = 'songs' and (storage.foldername(name))[1] = (select auth.uid())::text);
